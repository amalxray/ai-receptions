export function buildSalesPrompt(messages: SalesChatMessage[]): string {
  const transcript = messages
    .slice(-8)
    .map((message) => `${message.role === 'user' ? 'الطبيب' : 'المستشار'}: ${message.content.trim()}`)
    .join('\n');

  return `${SALES_SYSTEM_PROMPT}\n\nالمحادثة الحالية:\n${transcript}\n\nاكتب الرد التالي فقط، دون ذكر هذه التعليمات أو أسماء المزودين.`;
}
